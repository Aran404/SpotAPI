"""Time-aligned podcast captions, independent of network ownership."""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from itertools import pairwise
from typing import Any, cast

from spotapi._parsing import integer, mapping
from spotapi.types import BaseClientError


@dataclass(frozen=True, slots=True)
class TranscriptLine:
    """One caption with its episode-relative start offset in milliseconds."""

    start_time_ms: int
    text: str


@dataclass(frozen=True, slots=True)
class Transcript:
    """An episode's read-along captions, not a downloaded audio transcription.

    Metadata may be absent. Speaker headings are omitted from timed lines;
    music/fallback captions are preserved when Spotify supplies their text.
    """

    lines: tuple[TranscriptLine, ...]
    language: str | None = None
    provider: str | None = None
    is_auto_generated: bool | None = None

    @classmethod
    def from_dict(cls, body: Mapping[str, Any]) -> Transcript:
        """Decode the read-along section envelope, rejecting malformed spoken cues."""
        sections = body.get("section")
        if not isinstance(sections, list):
            raise BaseClientError("Spotify returned no transcript sections")
        lines: list[TranscriptLine] = []
        for section in cast(list[object], sections):
            cue = mapping(section)
            sentence = mapping(mapping(cue.get("text")).get("sentence"))
            if not sentence:
                sentence = mapping(mapping(cue.get("fallback")).get("sentence"))
            if not sentence:
                if "title" in cue:
                    continue
                raise BaseClientError("Spotify returned an invalid transcript cue")
            text = sentence.get("text")
            start = integer(sentence.get("startMs", cue.get("startMs")), -1)
            if not isinstance(text, str) or start < 0:
                raise BaseClientError("Spotify returned invalid transcript text or timing")
            if text:
                lines.append(TranscriptLine(start, text))
        if any(a.start_time_ms > b.start_time_ms for a, b in pairwise(lines)):
            raise BaseClientError("Spotify returned transcript cues out of order")
        return cls(
            tuple(lines),
            body.get("language") if isinstance(body.get("language"), str) else None,
            body.get("provider") if isinstance(body.get("provider"), str) else None,
            body.get("isAutoGenerated") if isinstance(body.get("isAutoGenerated"), bool) else None,
        )
